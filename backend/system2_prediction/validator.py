"""LLM validation of System 2 predictions.

PREDICTION -> the LLM reviews the prediction and its supporting evidence -> a structured validation.
The LLM does not produce a prediction. Its output is stored in `llm_validations`; the numeric
prediction row (predicted return, direction, sentiment, previous close, features) is never modified,
and no field the LLM returns is ever copied into it.

What is sent (build_payload): only information that was eligible at the prediction cut-off -
company, target session, cut-off, previous close, the model's predicted returns / directions /
uncertainty / contributions, relative sentiment, stored model features, the data-quality flag and the
news items the prediction actually used whose eligibility the run's availability policy allows
(headline, timestamps, availability, event type, sentiment). Never sent: actual closes / returns /
errors (even when a prediction has matured), news fetched or available after the cut-off, or
excluded (uncertain / date-only) news under a verified-only policy. `assert_no_leakage` re-checks the
payload before every call; a failing payload is NOT sent.
"""
from __future__ import annotations

import json
from collections import defaultdict
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.database.models import LLMValidation, NewsArticle, Prediction
from backend.services.llm import LLMError, LLMInvalidResponse, LLMProvider, redact
from backend.services.timeutil import iso_z, utcnow
from backend.system1_news.availability import POLICIES, eligibility

REVIEW_STATUSES = ["supported", "weakly_supported", "contradicted", "indeterminate"]
CUTOFF_CHECKS = ["passed", "failed", "uncertain"]
# Stored statuses when no review was obtained (never confused with a review result).
NOT_PERFORMED, VALIDATION_ERROR, API_ERROR = "not_performed", "validation_error", "api_error"

SYSTEM_PROMPT = """You are validating a financial market prediction generated by a deterministic prediction \
system for an Indian NIFTY 50 stock.

Rules:
- You must NOT create a new prediction. Never return a price, a return, a percentage move or a direction of \
your own, and never suggest a replacement number.
- You must NOT invent missing information. Use only the JSON supplied. If something important is not in it, \
list it under missing_information.
- You must NOT use information after the prediction cutoff (`prediction_cutoff`). Do not use your own \
knowledge of what happened later.

Evaluate whether the supplied evidence is consistent with the model's existing prediction. Check:
1. Whether the supplied news is relevant to the company (or, for MACRO items, to the market).
2. Whether the sentiment interpretation is reasonable. Positive wording is not the same as positive stock \
impact: "profit rises but misses estimates" is negative; a headline that only restates a price move that \
already happened (price_report=true) is not new information; higher inflation or yields are negative for \
equities.
3. Whether the event type is appropriate for the headline.
4. Whether the news was available before the cutoff, using `eligibility` / `available_at` / `fetched_at` \
(eligibility "verified" = held by the system before the cutoff).
5. Whether there are contradictory signals.
6. Whether important information is missing.
7. Whether the prediction appears supported, weakly_supported, contradicted or indeterminate based ONLY on \
the supplied evidence.

The model uses RELATIVE sentiment: news since the previous session's cutoff compared with the company's own \
usual headline tone. A positive raw score with a near-zero relative score is not a bullish signal. With no \
new news the model is designed to predict a move near zero (often NEUTRAL).

Return structured validation only. cutoff_check: "passed" if every supplied news item was available before \
the cutoff, "failed" if any was not, "uncertain" if availability cannot be established from the data."""

SCHEMA = {
    "type": "object",
    "properties": {
        "validation_status": {"type": "string", "enum": REVIEW_STATUSES},
        "reason": {"type": "string"},
        "key_supporting_factors": {"type": "array", "items": {"type": "string"}},
        "key_contradicting_factors": {"type": "array", "items": {"type": "string"}},
        "data_quality_issues": {"type": "array", "items": {"type": "string"}},
        "cutoff_check": {"type": "string", "enum": CUTOFF_CHECKS},
        "missing_information": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["validation_status", "reason", "key_supporting_factors", "key_contradicting_factors",
                 "data_quality_issues", "cutoff_check", "missing_information"],
    "additionalProperties": False,
}

FORBIDDEN_KEYS = {"actual", "actual_close", "actual_close_date", "actual_movement", "actual_movement_percent",
                  "actual_return", "actual_direction", "error", "abs_error", "squared_error", "direction_correct"}


def check_response(data: dict) -> list[str]:
    """Validate a model response against SCHEMA (exact keys, types, enums). Returns problems."""
    problems = []
    if not isinstance(data, dict):
        return ["response is not a JSON object"]
    extra = set(data) - set(SCHEMA["properties"])
    if extra:   # e.g. a replacement prediction the model was told not to give
        problems.append(f"unexpected fields: {sorted(extra)}")
    for key, spec in SCHEMA["properties"].items():
        if key not in data:
            problems.append(f"missing field: {key}")
            continue
        v = data[key]
        if spec["type"] == "string":
            if not isinstance(v, str):
                problems.append(f"{key} must be a string")
            elif "enum" in spec and v not in spec["enum"]:
                problems.append(f"{key}={v!r} not in {spec['enum']}")
        elif spec["type"] == "array":
            if not isinstance(v, list) or not all(isinstance(x, str) for x in v):
                problems.append(f"{key} must be a list of strings")
    if isinstance(data.get("reason"), str) and not data["reason"].strip():
        problems.append("reason is empty")
    return problems


def _ts(v) -> datetime | None:
    if not v:
        return None
    return datetime.fromisoformat(str(v).replace("Z", "")) if isinstance(v, str) else v


def assert_no_leakage(payload: dict, cutoff: datetime, info_time: datetime) -> None:
    """Raise LLMError if the payload contains outcome data or post-cut-off news."""
    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k in FORBIDDEN_KEYS:
                    raise LLMError(f"leakage check failed: outcome field '{k}' in payload")
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(payload)
    for n in payload.get("news_evidence", []):
        avail, fetched = _ts(n.get("available_at")), _ts(n.get("fetched_at"))
        if avail is not None and avail > cutoff:
            raise LLMError(f"leakage check failed: news {n.get('news_id')} available after the cut-off")
        if n.get("eligibility") == "verified" and (fetched is None or fetched > info_time):
            raise LLMError(f"leakage check failed: news {n.get('news_id')} fetched after the prediction")


def _run_times(p0: Prediction) -> tuple[datetime, datetime, str]:
    """(cut-off, information time, policy). Runs from before Phase 3 lack a stored cut-off: their
    information time (as_of) is used as the cut-off, and the policy defaults to verified-only."""
    run = p0.run
    as_of = (run.as_of if run else None) or p0.prediction_timestamp
    cutoff = (run.prediction_cutoff if run and run.prediction_cutoff else None) or as_of
    policy = (run.availability_policy if run and run.availability_policy else None) or "verified"
    return cutoff, min(as_of, cutoff), policy


def _eligible_news(session: Session, p0: Prediction, cutoff: datetime, info_time: datetime, policy: str) -> tuple[list, int]:
    """News the prediction used AND the policy allows, re-checked against the cut-off. Returns
    (items, number excluded)."""
    allowed = POLICIES.get(policy, POLICIES["verified"])
    out, excluded = [], 0
    snaps = p0.news_inputs
    if snaps is None:      # pre-Phase-3 run: rebuild from evidence ids, judged at the run's info time
        ids = list(p0.evidence_news_ids or [])
        arts = {a.id: a for a in session.scalars(select(NewsArticle).where(NewsArticle.id.in_(ids)))} if ids else {}
        snaps = []
        for i in ids:
            a = arts.get(i)
            if a is None:
                continue
            snaps.append({"news_id": a.id, "entity": None, "role": "raw_score_evidence", "title": a.title,
                          "source": a.source, "provider_published_at": iso_z(a.published_at),
                          "available_at": iso_z(a.published_at), "fetched_at": iso_z(a.fetched_at),
                          "timestamp_precision": a.timestamp_precision, "event_type": None,
                          "eligibility": eligibility(a.published_at, a.timestamp_precision, a.timezone_status,
                                                     a.fetched_at, info_time)})
    for x in snaps:
        avail = _ts(x.get("available_at"))
        if x.get("eligibility") not in allowed or (avail is not None and avail > cutoff):
            excluded += 1
            continue
        out.append({k: x.get(k) for k in ("news_id", "entity", "role", "title", "source", "provider_published_at",
                                          "available_at", "fetched_at", "timestamp_precision", "eligibility",
                                          "event_type", "price_report", "sentiment")})
    return out, excluded


def build_payload(session: Session, preds: list[Prediction]) -> dict:
    """All horizons for ONE company from one run, with only cut-off-eligible evidence."""
    p0 = preds[0]
    cutoff, info_time, policy = _run_times(p0)
    news, excluded = _eligible_news(session, p0, cutoff, info_time, policy)
    f0 = next((p.features for p in preds if p.features), None) or {}
    flow = f0.get("news_flow") or {}
    missing = [f"{p.horizon_label}: {p.missing_reason}" for p in preds if p.status != "OK"]
    missing += [f"model input '{k}' unavailable" for k, v in (f0.get("model_inputs") or {}).items() if v is None]
    if flow.get("status") == "insufficient_history":
        missing.append("relative sentiment unavailable: too little baseline news history")
    if flow.get("news_count") == 0:
        missing.append("no new company news since the previous session's cut-off")
    if excluded:
        missing.append(f"{excluded} news item(s) excluded: not eligible under the '{policy}' availability policy "
                       f"at the cut-off")
    run = p0.run
    today = next((p for p in preds if p.horizon_type == "today"), p0)
    return {
        "company": p0.company, "ticker": p0.ticker,
        "target_session": (run.target_session.isoformat() if run and run.target_session else today.target_date.isoformat()),
        "prediction_cutoff": iso_z(cutoff), "prediction_made_at": iso_z(info_time),
        "availability_policy": policy, "universe_version": run.universe_version if run else None,
        "model_version": p0.model_version, "data_quality_flag": p0.data_quality_flag,
        "previous_close": p0.previous_close,
        "previous_close_date": p0.previous_close_date.isoformat() if p0.previous_close_date else None,
        "predictions": [{
            "horizon": p.horizon_label, "target_date": p.target_date.isoformat(),
            "trading_days_ahead": p.trading_days_ahead,
            "predicted_return_percent": p.predicted_movement, "predicted_direction": p.predicted_direction,
            "uncertainty_1sigma_pct": p.uncertainty_1sigma_pct, "contributions_pct": p.contributions,
            "status": p.status, "missing_reason": p.missing_reason,
        } for p in preds],
        "relative_sentiment": {k: flow.get(k) for k in ("status", "current_sentiment", "relative_sentiment",
                                                        "sentiment_zscore", "baseline_mean", "baseline_std",
                                                        "baseline_n", "news_count", "news_recency_hours")},
        "raw_sentiment_score": today.sentiment_score,
        "macro_relative_sentiment": (f0.get("macro_news_flow") or {}).get("relative_sentiment"),
        "event_types": sorted({n["event_type"] for n in news if n.get("event_type")}),
        "model_features": f0.get("model_inputs"),
        "sentiment_input": f0.get("sentiment_input"),
        "known_missing_data": missing,
        "news_evidence": news,
    }


def validate_run(session: Session, run_id: str, llm: LLMProvider, tickers: list[str] | None = None) -> dict:
    """Review every company of a run. Never raises for LLM problems and never touches predictions."""
    q = select(Prediction).where(Prediction.run_id == run_id)
    if tickers:
        q = q.where(Prediction.ticker.in_(tickers))
    by_company: dict[str, list[Prediction]] = defaultdict(list)
    for p in session.scalars(q):
        by_company[p.ticker].append(p)
    results = {}
    for ticker, preds in by_company.items():
        payload = build_payload(session, preds)
        cutoff, info_time, _ = _run_times(preds[0])
        data, raw, err, req_status = {}, None, None, "ok"
        try:
            assert_no_leakage(payload, cutoff, info_time)
        except LLMError as exc:
            status, req_status, err = VALIDATION_ERROR, "leakage_blocked", str(exc)
        else:
            user = "Validate this model output. Data (JSON):\n" + json.dumps(payload, indent=1, default=str)
            try:
                data, raw = llm.complete_json(SYSTEM_PROMPT, user, SCHEMA)
                problems = check_response(data)
                if problems:
                    raise LLMInvalidResponse("response failed schema validation: " + "; ".join(problems))
                status = data["validation_status"]
            except LLMError as exc:
                req_status, err = exc.kind, redact(str(exc))
                status = {"not_configured": NOT_PERFORMED, "invalid_response": VALIDATION_ERROR}.get(exc.kind, API_ERROR)
                data = {}
            except Exception as exc:   # anything unexpected: record, never crash the pipeline
                req_status, err, status, data = "api_error", redact(f"{type(exc).__name__}: {exc}"), API_ERROR, {}
        reason = data.get("reason") or err or ""
        for p in preds:
            session.add(LLMValidation(
                prediction_id=p.id, provider=llm.name, model=llm.model, validation_status=status, confidence=None,
                inconsistencies=data.get("key_contradicting_factors", []),
                missing_information=data.get("missing_information", []), reasoning=reason,
                supporting_factors=data.get("key_supporting_factors", []),
                contradicting_factors=data.get("key_contradicting_factors", []),
                data_quality_issues=data.get("data_quality_issues", []), cutoff_check=data.get("cutoff_check"),
                request_status=req_status, error_message=err, request_payload=payload,
                raw_response=redact(raw), created_at=utcnow()))
        results[ticker] = {"validation_status": status, "validation_performed": req_status == "ok",
                           "request_status": req_status, "provider": llm.name, "model": llm.model, "reason": reason,
                           **{k: data.get(k) for k in ("key_supporting_factors", "key_contradicting_factors",
                                                       "data_quality_issues", "cutoff_check", "missing_information")}}
    session.flush()
    return results
